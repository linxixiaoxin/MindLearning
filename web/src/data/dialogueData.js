/**
 * 选题角度生成
 */
function genAngle(archA, archB, scene) {
  const comboKey1 = [archA.defenseDirection, archB.defenseDirection].sort().join('_')
  const comboKey2 = [archB.defenseDirection, archA.defenseDirection].sort().join('_')
  const dynamic = dynamicMap[comboKey1] || dynamicMap[comboKey2]

  const angles = [
    `当${archA.name}遇到${archB.name}——一个${archA.oneLiner}，一个${archB.oneLiner}。两种保护自己的方式，在同一个场景里碰撞。`,
    `${scene.title}——${archA.name}式的应对 vs ${archB.name}式的应对。哪一种更像你？`,
    `${archA.name}和${archB.name}，两种不同的防御在对话。他们都害怕被伤害，只是选择了相反的方向。`,
  ]

  if (dynamic) {
    angles.push(`${scene.title}里，${dynamic.pattern}的张力：${dynamic.tension}`)
  }

  return angles[Math.floor(Math.random() * angles.length)]
}

