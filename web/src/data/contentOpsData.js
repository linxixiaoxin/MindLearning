export function quickMatchScene(userInput) {
  if (!userInput || userInput.trim().length < 1) return []
  const input = userInput.trim()

  const boostDomains = new Set()
  for (const [word, domains] of Object.entries(emotionDomainMap)) {
    if (input.includes(word)) domains.forEach((d) => boostDomains.add(d))
  }

  const scored = scenes.map((scene) => {
    const text = `${scene.title}${scene.oneLiner}${scene.domain}${scene.stuck}`
    let score = 0
    if (text.includes(input)) score += 50
    for (const char of input) {
      if (char.trim() && text.includes(char)) score += 1
    }
    if (boostDomains.has(scene.domain)) score += 10
    return { scene, score }
  })

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((s) => s.scene)
}

export function getSceneAssets(sceneId) {
  const scene = scenes.find((s) => s.id === sceneId)
  if (!scene) return null

  const thinkerValues = Object.values(thinkers)
  return {
    scene,
    archetypes: scene.archetypes
      .map((name) => archetypes.find((a) => a.name === name))
      .filter(Boolean),
    thinkers: scene.thinkers
      .map((name) => thinkerValues.find((t) => t.name === name))
      .filter(Boolean),
  }
}

