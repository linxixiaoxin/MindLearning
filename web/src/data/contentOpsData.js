export function generateTopicAngle(sceneId, emotionKeyword) {
  const scene = scenes.find((s) => s.id === sceneId)
  if (!scene) return ''

  const archetypeName = scene.archetypes[0] || ''
  const archetype = archetypes.find((a) => a.name === archetypeName)
  const archetypeDesc = archetype ? archetype.oneLiner : ''

  const thinkerValues = Object.values(thinkers)
  const thinkerName = scene.thinkers[0] || ''
  const thinker = thinkerValues.find((t) => t.name === thinkerName)

  const preferredType = methodTypeMap[scene.stuck] || '表达'
  const method = methods.find((m) => m.type === preferredType) || methods[0]

  let emotionAngle = ''
  if (emotionKeyword) {
    const matched = emotionContentCoordinates.find(
      (e) => e.id === emotionKeyword || e.label === emotionKeyword,
    )
    if (matched && matched.topicAngles.length > 0) {
      const idx = sceneId.charCodeAt(sceneId.length - 1) % matched.topicAngles.length
      emotionAngle = matched.topicAngles[idx]
    }
  }

  const parts = [
    `「${scene.title}」`,
    archetype ? `${archetypeName}——${archetypeDesc}` : '',
    method ? `试试「${method.title}」` : '',
    emotionAngle || '',
  ].filter(Boolean)

  return parts.join(' · ')
}

