export function resolveLifeSceneId(sceneId) {
  if (lifeScenes.some((scene) => scene.id === sceneId)) return sceneId
  return defaultLifeSceneId
}

export function getLifeScene(sceneId) {
  const resolvedId = resolveLifeSceneId(sceneId || defaultLifeSceneId)
  return lifeScenes.find((scene) => scene.id === resolvedId) || lifeScenes[0]
}
