// ====== Helper: find archetype by name ======
export function findArchetype(name) {
  return archetypeContrasts.find(a => a.name === name)
}

// ====== Helper: generate contrast analysis ======
export function generateContrast(aName, bName, sceneTitle = '') {
  const a = findArchetype(aName)
  const b = findArchetype(bName)
  if (!a || !b) return null

  const sceneContext = sceneTitle ? `在「${sceneTitle}」这个处境下` : ''

  return {
    a,
    b,
    sceneContext,
    // Core pattern comparison
    patternDiff: generatePatternDiff(a, b),
    // Emotional style comparison
    emotionDiff: generateEmotionDiff(a, b),
    // Workplace manifestation comparison
    workplaceDiff: generateWorkplaceDiff(a, b),
    // Topic angles
    topicAngles: generateTopicAngles(a, b, sceneTitle),
  }
}

function generatePatternDiff(a, b) {
  return `${a.name}的运转模式是：${a.gap} → ${a.defense} → ${a.script.split('→')[0] || ''}。而${b.name}的运转模式是：${b.gap} → ${b.defense} → ${b.script.split('→')[0] || ''}。关键差异在于防御方向：${a.defense} vs ${b.defense}。`
}

function generateEmotionDiff(a, b) {
  return `${a.name}的情感风格是「${a.emotionalStyle || a.defense}」，他们相信「${a.fear}」。${b.name}的情感风格是「${b.emotionalStyle || b.defense}」，他们相信「${b.fear}」。`
}

function generateWorkplaceDiff(a, b) {
  const aW = a.workplace || `在工作中，${a.name}的核心模式是「${a.defense}」`
  const bW = b.workplace || `在工作中，${b.name}的核心模式是「${b.defense}」`
  return `${aW}。而${bW}。`
}

function generateTopicAngles(a, b, sceneTitle = '') {
  const base = `同样是${a.gap.includes('不') ? a.gap : '不被满足'}`

  return [
    {
      title: `「${a.name} × ${b.name}：${a.defense.split('—')[0] || a.defense} vs ${b.defense.split('—')[0] || b.defense}」`,
      hook: `${sceneTitle ? '在「' + sceneTitle + '」这个处境下——' : ''}${a.name}在${a.fear}，${b.name}在${b.fear}。同一个世界的两种活法。`,
      body: `缺口是一样的（${a.gap}），但防御不同（${a.defense} vs ${b.defense}），于是人生完全不同。这不是对错，是自动导航的差异。`,
    },
    {
      title: `「如果你是${a.name}，别学${b.name}——但可以借他一个视角」`,
      hook: `${base}——${a.name}选${a.defense}不是因为懦弱，是这是ta唯一会的活法。${b.name}选${b.defense}也是。`,
      body: `${a.ifsRole}型的${a.name}需要的是${a.unfinished || '被真正承接'}。${b.ifsRole}型的${b.name}需要的是${b.unfinished || '被真正看见'}。两种保护策略，指向同一个深层渴望。`,
    },
    {
      title: `「职场版：一个${a.name}和一个${b.name}做同一个项目会怎样」`,
      hook: `${a.name}在团队里是「${a.workplace || '会用自己的防御方式做事'}」的。${b.name}是「${b.workplace || '会用另一种防御方式做事'}」的。`,
      body: `两种模式在同一个处境下碰撞——不是谁对谁错，是两套操作系统的冲突与互补。`,
    },
  ]
}
